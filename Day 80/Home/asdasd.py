

def main():
    try:
        a = float(input("შეიყვანეთ პირველი რიცხვი: ").strip())
        b = float(input("შეიყვანეთ მეორე რიცხვი: ").strip())
    except ValueError:
        print("შეყვანა არასწორია — გთხოვთ დააჭიროთ ნამდვილი რიცხვი.")
        return

    print("ჯამი:", a + b)
    print("სხვაობა (a - b):", a - b)
    print("ნამრავლი:", a * b)
    if b != 0:
        print("განაყოფი (a / b):", a / b)
    else:
        print("განაყოფი (a / b): განაყოფა არასწორია (გაყოფა 0-ით).")

    print("5-ის კვადრატი (5**2):", 5 ** 2)
    print("5-ის კუბი (5**3):", 5 ** 3)

  
    print("17-ში 5 რამდენჯერ შედის (17 // 5):", 17 // 5)
    print("17-ში 5 ნაშთი (17 % 5):", 17 % 5)

if __name__ == "__main__":
    main()